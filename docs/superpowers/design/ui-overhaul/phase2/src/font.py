def rows_of(ch):
    """The glyph as (rows, top row in the cell)."""
    src = G[ch]
    if src.startswith('x:'):
        return src[2:].split('|'), X_TOP
    return src.split('|'), CAP_TOP


def glyph(ch):
    """A 12 x 16 cell holding one glyph, left aligned."""
    c = Cv(CELL_W, CELL_H)
    rows, top = rows_of(ch)
    for j, r in enumerate(rows):
        for i, v in enumerate(r):
            if v == '#':
                c.px(i, top + j, 0xFFFFFFFF)
    return c


def width(c):
    b = c.bounds()
    return 0 if b is None else b[2] + 1


def compose(base, mark):
    lower = base.islower()
    src = '\u0131' if base == 'i' else base
    g = glyph(src)
    m = NARROW[mark] if base == 'i' else MARKS[mark]
    w, mw = width(g), len(m[0])
    out = Cv(CELL_W, CELL_H)
    gx = max(0, (mw - w + 1) // 2)
    out.blit(g, gx, 0)
    top = (X_TOP if lower else CAP_TOP) - len(m) - (1 if len(m) < 3 else 0)
    mx = gx + (w - mw) // 2
    for j, r in enumerate(m):
        for i, v in enumerate(r):
            if v == '#':
                out.px(mx + i, top + j, 0xFFFFFFFF)
    return out


def with_cedilla(base):
    g = glyph(base)
    x = (width(g) - 4) // 2
    for j, r in enumerate(CEDILLA):
        for i, v in enumerate(r):
            if v == '#':
                g.px(x + i, 14 + j, 0xFFFFFFFF)
    return g


def flipped(ch):
    """Inverted punctuation: the mark upside down, hanging from the x line."""
    g = glyph(ch)
    b = g.bounds()
    out = Cv(CELL_W, CELL_H)
    for y in range(b[1], b[3] + 1):
        for x in range(b[0], b[2] + 1):
            if g.get(x, y):
                out.px(b[2] - x, X_TOP - 1 + (b[3] - y), 0xFFFFFFFF)
    return out


def all_glyphs():
    out = {ch: glyph(ch) for ch in G if ch != '\u0131'}
    out['\u0131'] = glyph('\u0131')
    for mark, bases in COMPOSED.items():
        for b in bases:
            out[CODES[mark][b]] = compose(b, mark)
    out['\u00c7'], out['\u00e7'] = with_cedilla('C'), with_cedilla('c')
    out['\u00a1'], out['\u00bf'] = flipped('!'), flipped('?')
    return out


def order(glyphs):
    ascii_ = [chr(i) for i in range(33, 127)]
    rest = sorted(c for c in glyphs if c not in ascii_)
    return [c for c in ascii_ if c in glyphs] + rest


def text(glyphs, s, c=0xFFFFFFFF, space=5):
    """Set a line the way Minecraft will: each glyph trimmed to its width, 1 texel between glyphs."""
    xs, x = [], 0
    for ch in s:
        if ch == ' ':
            x += space
            continue
        g = glyphs[ch]
        xs.append((g, x))
        x += width(g) + 1
    cv = Cv(max(1, x - 1), CELL_H)
    for g, gx in xs:
        cv.stamp(gx, 0, g, c)
    return cv


def styled(glyphs, s, bands, outline, shadow):
    """A title as the hub will draw it: banded fill, 1 texel outline, a drop shadow."""
    m = text(glyphs, s)
    body = Cv(m.w + 2, m.h + 3)
    for y in range(m.h):
        for x in range(m.w):
            if m.d[y * m.w + x]:
                body.px(x + 1, y + 1, bands[min(len(bands) - 1, max(0, (y - CAP_TOP) * len(bands) // 11))])
    body.outline(outline)
    out = Cv(body.w + 1, body.h + 1)
    sh = Cv(body.w, body.h)
    sh.d = [shadow if v else 0 for v in body.d]
    return out.blit(sh, 1, 1).blit(body, 0, 0)


